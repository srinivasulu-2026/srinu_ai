# Task 1: Variables and Data Types
name = "Srinu"         
age = 36               
height = 5.9          
is_student = True     
# Printing all four values in a single print statement
print(name, age, height, is_student)
# Task 2: String Formatting
# Using f-strings for clean formatting
print(f"Name: {name} | Age: {age} | Height: {height} | Student: {is_student}")
# Task 3: Arithmetic Operations
age_in_months = age * 12
age_in_days = age * 365
remainder_by_7 = age % 7
age_squared = age ** 2

print("Age in months:", age_in_months)
print("Age in days:", age_in_days)
print("The Remainder when age is divided by 7:", remainder_by_7)
print("Age raised to the power of 2:", age_squared)